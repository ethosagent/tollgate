package testkit

import (
	"reflect"
	"runtime"

	"github.com/ethosagent/tollgate"
)

// The core offers a Hook only the stages it implements itself: a method
// promoted from an embedded tollgate.NoopHook is skipped (and, for OnEvent
// and After, no event tap is built). The harness must offer the same stages,
// or a Recording would show calls production never makes and the run would
// take a code path production does not. overrides mirrors the core's rule
// (internal/chain/detect.go); TestRun_RecordsOnlyOverriddenStages holds the
// two to the same cases.

var noopType = reflect.TypeFor[tollgate.NoopHook]()

// overrides reports whether h implements method itself rather than through
// an embedded NoopHook. When in doubt it answers true.
func overrides(h tollgate.Hook, method string) bool {
	return !promotedFromNoop(reflect.TypeOf(h), method)
}

// promotedFromNoop follows Go's selector rule down the embedding tree.
func promotedFromNoop(t reflect.Type, method string) bool {
	if t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == noopType {
		return true
	}
	if t.Kind() != reflect.Struct || declares(t, method) || declares(reflect.PointerTo(t), method) {
		return false
	}
	f, ok := provider(t, method)
	return ok && promotedFromNoop(f, method)
}

// declares reports whether t's method is its own code rather than a wrapper
// the compiler generated (those report the file "<autogenerated>").
func declares(t reflect.Type, method string) bool {
	m, ok := t.MethodByName(method)
	if !ok {
		return false
	}
	fn := runtime.FuncForPC(m.Func.Pointer())
	if fn == nil {
		return true
	}
	file, _ := fn.FileLine(fn.Entry())
	return file != "<autogenerated>"
}

// provider returns the type of the single embedded field of struct t whose
// method set has method; ok is false when there is not exactly one.
func provider(t reflect.Type, method string) (reflect.Type, bool) {
	var found reflect.Type
	n := 0
	for i := range t.NumField() {
		f := t.Field(i)
		if !f.Anonymous {
			continue
		}
		ft := f.Type
		if ft.Kind() == reflect.Pointer {
			ft = ft.Elem()
		}
		if _, ok := reflect.PointerTo(ft).MethodByName(method); ok {
			found, n = ft, n+1
		}
	}
	return found, n == 1
}
