package methodset

import (
	"reflect"
	"runtime"
)

// PromotedFrom reports whether t's method (t or *t) is origin's, reached only
// through embedding: no type on the way declares it and the one embedded
// field that provides it leads to origin. It answers false whenever it
// cannot prove that, so a caller that skips promoted methods never skips
// real code.
func PromotedFrom(t reflect.Type, method string, origin reflect.Type) bool {
	if t == nil {
		return false
	}
	if t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == origin {
		return true
	}
	if t.Kind() != reflect.Struct || Declares(t, method) {
		return false
	}
	f, ok := provider(t, method)
	return ok && PromotedFrom(f, method, origin)
}

// Declares reports whether t (or *t; t may be either) has method in its own
// code, with a value or a pointer receiver, rather than through a wrapper
// the compiler generated for a promoted method.
func Declares(t reflect.Type, method string) bool {
	if t == nil {
		return false
	}
	if t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	return own(t, method) || own(reflect.PointerTo(t), method)
}

// own reports whether t's method is its own code. Generated wrappers (for a
// promoted method, or for a value method called through a pointer) report
// the file "<autogenerated>".
func own(t reflect.Type, method string) bool {
	m, ok := t.MethodByName(method)
	if !ok {
		return false
	}
	fn := runtime.FuncForPC(m.Func.Pointer())
	if fn == nil {
		return true
	}
	file, _ := fn.FileLine(fn.Entry())
	return file != "<autogenerated>"
}

// provider returns the type of the single embedded field of struct t whose
// method set (value or pointer) has method; ok is false when there is not
// exactly one.
func provider(t reflect.Type, method string) (reflect.Type, bool) {
	var found reflect.Type
	n := 0
	for i := range t.NumField() {
		f := t.Field(i)
		if !f.Anonymous {
			continue
		}
		ft := f.Type
		if ft.Kind() == reflect.Pointer {
			ft = ft.Elem()
		}
		if _, ok := reflect.PointerTo(ft).MethodByName(method); ok {
			found, n = ft, n+1
		}
	}
	return found, n == 1
}
