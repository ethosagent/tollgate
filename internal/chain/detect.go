package chain

import (
	"reflect"
	"runtime"

	"github.com/ethosagent/tollgate/internal/model"
)

var noopType = reflect.TypeFor[model.NoopHook]()

// overrides reports whether h implements method itself rather than through
// an embedded model.NoopHook. It runs once per hook, when the hook joins a
// Chain, so the request path never pays for it. It answers true whenever it
// cannot prove the method is NoopHook's no-op: a wrong "true" costs a no-op
// call, a wrong "false" would silently drop a hook.
func overrides(h model.Hook, method string) bool {
	return !promotedFromNoop(reflect.TypeOf(h), method)
}

// promotedFromNoop follows Go's selector rule down the embedding tree: the
// method is NoopHook's if no type on the way declares it and the one embedded
// field that provides it leads to NoopHook.
func promotedFromNoop(t reflect.Type, method string) bool {
	if t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == noopType {
		return true
	}
	if t.Kind() != reflect.Struct || declares(t, method) || declares(reflect.PointerTo(t), method) {
		return false
	}
	f, ok := provider(t, method)
	return ok && promotedFromNoop(f, method)
}

// declares reports whether t's method is its own code rather than a wrapper
// the compiler generated for a promoted method (or for a value method called
// through a pointer); those report the file "<autogenerated>".
func declares(t reflect.Type, method string) bool {
	m, ok := t.MethodByName(method)
	if !ok {
		return false
	}
	fn := runtime.FuncForPC(m.Func.Pointer())
	if fn == nil {
		return true
	}
	file, _ := fn.FileLine(fn.Entry())
	return file != "<autogenerated>"
}

// provider returns the type of the single embedded field of struct t whose
// method set (value or pointer) has method; ok is false when there is not
// exactly one.
func provider(t reflect.Type, method string) (reflect.Type, bool) {
	var found reflect.Type
	n := 0
	for i := range t.NumField() {
		f := t.Field(i)
		if !f.Anonymous {
			continue
		}
		ft := f.Type
		if ft.Kind() == reflect.Pointer {
			ft = ft.Elem()
		}
		if _, ok := reflect.PointerTo(ft).MethodByName(method); ok {
			found, n = ft, n+1
		}
	}
	return found, n == 1
}
